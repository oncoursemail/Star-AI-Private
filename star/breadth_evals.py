"""Breadth suites: GDScript (graded by running the answer in headless Godot) and instruction following (code checks).

    python -m star.evals run      --suite evals/gdscript/golden-tasks-v1.json        --out evals/results/x.json
    python -m star.evals run      --suite evals/instruction-following/holdout-v1.json --out evals/results/y.json
    python -m star.evals selftest --suite evals/gdscript/holdout-v1.json              # no model: references pass, bad ones fail

`python -m star.evals` hands a suite to this module when every task carries `auto.breadth.kind`. The answer path
(STAR's own run_task, isolated APPDATA, quiet-lock and planner waits, checkpointing, resume) is the one
`star.eval_runner.run_suite` already provides; only the scorer differs. star/eval_runner.py, eval_checks.py and
eval_sandbox.py are not changed, so the sealed grader fingerprint of the Luau suites does not move. The breadth
graders have their own fingerprint, `breadth_grader_sha256`, written to the result file and folded into the run
fingerprint, so a result made with different grader code is never resumed or compared as the same run.

GDScript tasks: the fenced script from the answer is saved as `answer.gd` next to the task's harness test
(`tests/<id>.gd`, which extends SceneTree) and `harness.gd`, and run with `godot --headless -s test.gd`. The test
prints `@@T<TAB>pass|fail<TAB>name` lines like the Luau harness. Where it runs (never on the model server):
  STAR_EVAL_GODOT_SSH   user@host of a machine that has Godot 4 (brain 2); the script runs there at nice 19 under limits
  STAR_EVAL_GODOT_BIN   path of the Godot binary (default ~/godot/godot on that host; on this PC: `godot` on PATH)
With neither set, a GDScript task is `error` (infrastructure), never `fail`.
Model-written code is run, so the answer is first scanned for file, network, OS and runtime-eval APIs (a task never
needs them) and refused with a failed `sandbox_policy` check if one appears; the remote run also drops the network
(`unshare -rn` when allowed), uses a throw-away directory and HOME, and caps CPU, memory, file size and wall time.
"""
