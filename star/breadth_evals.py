ROOT = Path(__file__).resolve().parents[1]
KINDS = ("gdscript", "ifbench")
GODOT_PROJECT = '; generated by star.breadth_evals\nconfig_version=5\n\n[application]\nconfig/name="star-breadth-eval"\n'
_SSH_TARGET = re.compile(r"^[A-Za-z0-9._-]{1,32}@[A-Za-z0-9._:-]{1,80}$")
_BINARY = re.compile(r"^(?:~|\$HOME)?/?[A-Za-z0-9._/-]{1,200}$")
_FILE_NAME = re.compile(r"^[A-Za-z0-9_.-]{1,40}$")
OUTPUT_CAP = 65_536


def _lf(data: bytes) -> bytes:
    return data.replace(b"\r\n", b"\n")


def breadth_grader_sha256(suite_dir: Path | None = None) -> str:
    """Fingerprint of the code (and the shared GDScript harness) that computes breadth grades."""
    digest = hashlib.sha256()
    for name in ("breadth_evals.py", "breadth_ifbench.py"):
        digest.update(name.encode() + b"\0" + _lf((ROOT / "star" / name).read_bytes()))
    harness = Path(suite_dir) / "harness.gd" if suite_dir else None
    if harness is not None and harness.is_file():
        digest.update(b"harness.gd\0" + _lf(harness.read_bytes()))
    return digest.hexdigest()


# --- reading a GDScript answer ----------------------------------------------------------------------

GD_FENCE = re.compile(r"```[ \t]*(?:gdscript|gd|godot)\b[^\n]*\n(.*?)```", re.S | re.I)
_LOOKS_LIKE_GD = re.compile(r"^\s*(?:extends|class_name|func|var|signal|@export|@tool)\b", re.M)


def extract_gdscript_blocks(body: str) -> list[str]:
    labelled = [m.group(1) for m in GD_FENCE.finditer(body) if m.group(1).strip()]
    if labelled:
        return labelled
    return [m.group(1) for m in checks.PLAIN_FENCE.finditer(body) if _LOOKS_LIKE_GD.search(m.group(1))]


def pick_script(blocks: list[str]) -> str:
    """The longest block that declares what it extends (the script); else the longest block."""
    scripts = [b for b in blocks if re.search(r"^\s*(?:extends|class_name)\b", b, re.M)]
    return max(scripts or blocks, key=len) if blocks else ""


def strip_gdscript(code: str) -> str:
    """Comments and string contents removed (line breaks kept): what a static scan should look at."""
    out, i, n = [], 0, len(code)
    while i < n:
        c = code[i]
        if c == "#":
            j = code.find("\n", i)
            i = n if j == -1 else j
            continue
        if c in "\"'":
            quote = code[i:i + 3] if code.startswith(c * 3, i) else c
            j = i + len(quote)
            while j < n and not code.startswith(quote, j):
                j += 2 if code[j] == "\\" else 1
            out.append("\n" * code.count("\n", i, min(j + len(quote), n)) + '""')
            i = min(j + len(quote), n)
            continue
        out.append(c)
        i += 1
    return "".join(out)


# A task never needs files, sockets, processes or runtime-compiled code; refusing them keeps the run inside the project.
_FORBIDDEN = re.compile(
    r"\b(?:OS|FileAccess|DirAccess|HTTPClient|HTTPRequest|TCPServer|StreamPeer\w*|PacketPeer\w*|UDPServer|WebSocket\w*|"
    r"WebRTC\w*|ENetConnection|ENetMultiplayerPeer|Expression|ClassDB|JavaClassWrapper|JavaScriptBridge|ResourceLoader|"
    r"ResourceSaver|GDExtension\w*|ConfigFile|Thread|source_code|get_singleton|load_resource_pack|"
    r"str_to_var|bytes_to_var_with_objects|var_to_bytes_with_objects|OpenXR\w*|XRServer)\b|GDScript\s*\.\s*new")


def forbidden_apis(code: str) -> list[str]:
    return sorted({m.group(0).replace(" ", "") for m in _FORBIDDEN.finditer(strip_gdscript(code))})


# --- running Godot ----------------------------------------------------------------------------------

class GodotRunner:
    """Run a Godot project given as {file name: text} with `-s test.gd` and return a SandboxResult."""

    def __init__(self, ssh: str = "", binary: str = "", *, wall_s: int = 20, cpu_s: int = 15, mem_mb: int = 6144,
                 runner=subprocess.run):
        if ssh and not _SSH_TARGET.fullmatch(ssh):
            raise ValueError("SSH target must look like user@address")
        if binary and not _BINARY.fullmatch(binary):
            raise ValueError("invalid Godot binary path")
        for value in (wall_s, cpu_s, mem_mb):
            if type(value) is not int or not 1 <= value <= 16384:
                raise ValueError("limits must be small positive integers")
        self.ssh, self.binary = ssh, binary
        self.wall_s, self.cpu_s, self.mem_mb = wall_s, cpu_s, mem_mb
        self._runner = runner

    @classmethod
    def from_env(cls, ssh: str = "", binary: str = "") -> "GodotRunner | None":
        ssh = ssh or os.environ.get("STAR_EVAL_GODOT_SSH", "")
        binary = binary or os.environ.get("STAR_EVAL_GODOT_BIN", "")
        if not ssh and not (binary or shutil.which("godot")):
            return None
        return cls(ssh, binary)

    def remote_script(self, files: dict[str, str]) -> str:
        for name in files:
            if not _FILE_NAME.fullmatch(name):
                raise ValueError("invalid file name")
        binary = self.binary or "~/godot/godot"
        if binary.startswith("~/"):
            binary = "$HOME/" + binary[2:]
        lines = [f'BIN="{binary}"',
                 '[ -x "$BIN" ] || { echo "@@NOGODOT"; exit 96; }',
                 "D=$(mktemp -d /tmp/stargd.XXXXXXXX) || exit 97", 'cd "$D" || exit 97',
                 "trap 'cd /; rm -rf \"$D\"' EXIT", "mkdir proj && cd proj"]
        for name, text in files.items():
            lines += [f"base64 -d > {name} <<'STAR_EOF'", base64.b64encode(text.encode("utf-8")).decode("ascii"), "STAR_EOF"]
        lines += ['export HOME="$D" XDG_DATA_HOME="$D/xd" XDG_CONFIG_HOME="$D/xc" XDG_CACHE_HOME="$D/xk"',
                  'NS=""; unshare -rn true 2>/dev/null && NS="unshare -rn"',
                  f"( ulimit -v {self.mem_mb * 1024}; ulimit -t {self.cpu_s}; ulimit -f 2048; ulimit -c 0; "
                  f'exec $NS nice -n 19 timeout -s KILL {self.wall_s} "$BIN" --headless --path . -s test.gd 2>&1 ) '
                  f"| head -c {OUTPUT_CAP}",
                  'echo "@@RC ${PIPESTATUS[0]}"', ""]
        return "\n".join(lines)

    def run(self, files: dict[str, str]) -> SandboxResult:
        started = monotonic()
        try:
            if self.ssh:
                done = self._runner(["ssh", "-o", "BatchMode=yes", "-o", "ConnectTimeout=10", self.ssh, "bash -s"],
                                    input=self.remote_script(files).encode("utf-8"), capture_output=True,
                                    timeout=self.wall_s + 40)
                text = done.stdout.decode("utf-8", "replace")
                if done.returncode != 0 and "@@RC" not in text:
                    return SandboxResult(error=f"ssh failed (status {done.returncode})", seconds=monotonic() - started)
                rc, output = parse_status(text)
            else:
                rc, output = self._run_local(files)
        except subprocess.TimeoutExpired:
            return SandboxResult(error="the Godot run timed out at the ssh/process level", seconds=monotonic() - started)
        except OSError as exc:
            return SandboxResult(error="could not start the runner (" + type(exc).__name__ + ")", seconds=monotonic() - started)
        if "@@NOGODOT" in output:
            return SandboxResult(error="no Godot binary at the configured path", seconds=monotonic() - started)
        return SandboxResult(rc=rc, stdout=output, timed_out=rc in (124, 137, 9, 152) and "@@DONE" not in output,
                             seconds=round(monotonic() - started, 2))

    def _run_local(self, files: dict[str, str]) -> tuple[int, str]:
        binary = shutil.which(self.binary or "godot") or self.binary
        with tempfile.TemporaryDirectory(prefix="stargd-") as folder:
            project = Path(folder) / "proj"
            project.mkdir()
            for name, text in files.items():
                (project / name).write_text(text, encoding="utf-8", newline="\n")
            home = Path(folder) / "home"
            home.mkdir()
            env = {**os.environ, "HOME": str(home), "APPDATA": str(home), "XDG_DATA_HOME": str(home / "d"),
                   "XDG_CONFIG_HOME": str(home / "c"), "XDG_CACHE_HOME": str(home / "k")}
            flags = getattr(subprocess, "BELOW_NORMAL_PRIORITY_CLASS", 0) | getattr(subprocess, "CREATE_NO_WINDOW", 0)
            try:
                done = self._runner([binary, "--headless", "--path", str(project), "-s", "test.gd"], cwd=project, env=env,
                                    capture_output=True, timeout=self.wall_s, creationflags=flags)
            except subprocess.TimeoutExpired:
                return 124, ""
            return done.returncode, (done.stdout + done.stderr).decode("utf-8", "replace")[:OUTPUT_CAP]


def parse_gd_output(stdout: str) -> checks.UnitOutcome:
    """The Luau harness's `@@` protocol, plus the first Godot script error as the reason a script did not run."""
    outcome = checks.parse_test_output(stdout)
    errors = [ln.strip() for ln in stdout.splitlines() if "SCRIPT ERROR" in ln or "Parse Error" in ln]
    if errors:
        first = re.sub(r"^SCRIPT ERROR:\s*", "", errors[0])[:200]
        if outcome.load_error:
            outcome.load_error = f"{outcome.load_error} ({first})"[:300]
        elif not outcome.done and not outcome.error:
            outcome.error = first
    return outcome


def score_gdscript(task: dict, answer: str, *, test_body: str, harness: str, runner: GodotRunner | None) -> checks.TaskScore:
    auto = task["auto"]
    score = checks.TaskScore()
    body, _ = checks.split_answer(answer or "")
    blocks = extract_gdscript_blocks(body)
    score.blocks = len(blocks)
    score.checks.append(checks.Check("gdscript_block", bool(blocks), "" if blocks else "no fenced GDScript block in the answer"))
    if not blocks:
        return score
    script = pick_script(blocks)
    banned = forbidden_apis(script)
    if banned:
        score.checks.append(checks.Check("sandbox_policy", False, "uses APIs the eval does not allow: " + ", ".join(banned)))
        return score
    if runner is None:
        raise checks.InfraError("no Godot runner: set STAR_EVAL_GODOT_SSH (or STAR_EVAL_GODOT_BIN)")
    started = monotonic()
    run = runner.run({"project.godot": GODOT_PROJECT, "harness.gd": harness, "answer.gd": script, "test.gd": test_body})
    score.timings["godot_s"] = round(monotonic() - started, 2)
    if run.error:
        raise checks.InfraError("godot runner: " + run.error[:120])
    for check in checks.unit_checks(parse_gd_output(run.stdout), run, auto["unit_test"].get("checks")):
        check.detail = check.detail.replace("in the Luau VM", "in headless Godot")
        score.checks.append(check)
    return score


def score_ifbench(task: dict, answer: str) -> checks.TaskScore:
    from .breadth_ifbench import check_all
    score = checks.TaskScore()
    body, _ = checks.split_answer(answer or "")
    score.checks.append(checks.Check("answer", bool(body.strip()), "" if body.strip() else "empty answer"))
    if not body.strip():
        return score
    for cid, reason in check_all(body, task["auto"]["breadth"]["constraints"]):
        score.checks.append(checks.Check(cid, not reason, reason))
    return score


def make_scorer(suite, runner: GodotRunner | None):
    harness_file = suite.directory / "harness.gd"
    harness = harness_file.read_text(encoding="utf-8").replace("\r\n", "\n") if harness_file.is_file() else ""

    def scorer(task: dict, answer: str) -> checks.TaskScore:
        kind = task["auto"]["breadth"]["kind"]
        if kind == "ifbench":
            return score_ifbench(task, answer)
        return score_gdscript(task, answer, test_body=suite.test_body(task), harness=harness, runner=runner)
    return scorer


# --- suite detection and validation --------------------------------------------------------------------

def suite_kind(path: Path) -> str:
    """'gdscript' / 'ifbench' when every task of the suite file carries auto.breadth.kind of one kind; else ''."""
    try:
        tasks = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return ""
    kinds = {((t.get("auto") or {}).get("breadth") or {}).get("kind") for t in tasks if isinstance(t, dict)} if isinstance(tasks, list) else set()
    return kinds.pop() if len(kinds) == 1 and next(iter(kinds)) in KINDS else ""


def breadth_problems(tasks: list[dict], directory: Path) -> list[str]:
    from .breadth_ifbench import validate_constraints
    problems = []
    for t in tasks:
        spec = (t.get("auto") or {}).get("breadth") or {}
        if spec.get("kind") == "ifbench":
            problems += [f"{t['id']}: {p}" for p in validate_constraints(spec.get("constraints") or [])]
            if not spec.get("constraints"):
                problems.append(f"{t['id']}: no constraints")
        elif spec.get("kind") == "gdscript":
            unit = (t.get("auto") or {}).get("unit_test") or {}
            if not unit.get("file") or not isinstance(unit.get("checks"), int):
                problems.append(f"{t['id']}: gdscript task needs auto.unit_test with file and checks")
        else:
            problems.append(f"{t['id']}: unknown breadth kind {spec.get('kind')!r}")
    return problems


# --- selftest: references must pass, bad answers and the empty answer must fail --------------------------

def selftest(suite, scorer, *, log=print) -> int:
    failures = 0
    ref_dir = suite.directory / "reference"
    for task in suite.runnable():
        alternatives = [(f".{f.stem[len(task['id']) + 1:]}", True) for f in sorted(ref_dir.glob(f"{task['id']}.alt*.md"))]
        for kind, expect in (("", True), (".bad", False), *alternatives):   # .alt*.md: other correct answers must pass too
            file = ref_dir / f"{task['id']}{kind}.md"
            if not file.is_file():
                log(f"FAIL {task['id']}{kind or ' reference'}: file missing")
                failures += 1
                continue
            try:
                score = scorer(task, file.read_text(encoding="utf-8"))
            except checks.InfraError as exc:
                log(f"{task['id']}{kind or ' reference'}: infrastructure: {exc}")
                failures += 1
                continue
            good = score.passed == expect
            failures += 0 if good else 1
            log(f"{'ok  ' if good else 'FAIL'} {task['id']}{kind or ' reference'} "
                f"(expected {'pass' if expect else 'fail'}, got {'pass' if score.passed else 'fail'})"
                + ("" if good or not expect else ": " + "; ".join(score.reasons)[:240])
                + (f" [fails: {'; '.join(score.reasons)[:120]}]" if good and not expect else ""))
        if scorer(task, "").passed:
            failures += 1
            log(f"FAIL {task['id']}: an empty answer passed")
    return failures


# --- command line (called from star.evals) ----------------------------------------------------------------

def main(args: list[str]) -> int:
    """`run`, `selftest` and `rescore` for a breadth suite; the same options as star.eval_runner plus --godot-ssh/--godot-bin."""
    from . import eval_runner as er
    parser = argparse.ArgumentParser(prog="python -m star.evals")
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("run", "selftest", "rescore"):
        p = sub.add_parser(name)
        er.add_common(p)
        p.add_argument("--godot-ssh", default="", help="user@host that has Godot 4 (or STAR_EVAL_GODOT_SSH)")
        p.add_argument("--godot-bin", default="", help="Godot binary path on that host (or STAR_EVAL_GODOT_BIN)")
        if name != "selftest":
            p.add_argument("--out", required=True, type=Path)
        if name == "run":
            p.add_argument("--tasks", default="")
            p.add_argument("--no-resume", action="store_true")
            p.add_argument("--retry-errors", action="store_true")
        if name == "rescore":
            p.add_argument("--result", required=True, type=Path)
    ns = parser.parse_args(args)
    suite = er.load_suite(ns.suite)
    problems = breadth_problems(suite.tasks, suite.directory)
    if problems:
        raise SystemExit("breadth suite is invalid: " + "; ".join(problems[:8]))
    kind = suite_kind(ns.suite)
    runner = GodotRunner.from_env(ns.godot_ssh, ns.godot_bin) if kind == "gdscript" else None
    scorer = make_scorer(suite, runner)
    if ns.command == "selftest":
        failures = selftest(suite, scorer)
        print("selftest:", "all good" if not failures else f"{failures} problem(s)")
        return 1 if failures else 0
    if ns.command == "rescore":
        done = er.rescore(suite, json.loads(ns.result.read_text(encoding="utf-8")), scorer)
        done["run"]["breadth_grader_sha256"] = breadth_grader_sha256(suite.directory)
        er.write_result(ns.out, done)
        print(json.dumps(done["summary"]))
        return 0
    ns._suite = suite
    run_info, ask, _luau_scorer, probe, secrets = er.build_real(ns)
    grader = breadth_grader_sha256(suite.directory)
    run_info["breadth"] = {"kind": kind, "grader_sha256": grader,
                           "godot_runner": ("ssh" if runner and runner.ssh else "local" if runner else "none")}
    run_info["fingerprint"] = hashlib.sha256((run_info["fingerprint"] + grader).encode()).hexdigest()[:12]
    from .planner_client import PlannerClient
    planner = PlannerClient(timeout=3.0)
    result = er.run_suite(suite, out=ns.out, ask=ask, scorer=scorer, lock_probe=probe, run_info=run_info,
                          task_ids=[x for x in ns.tasks.split(",") if x] or None, resume=not ns.no_resume,
                          retry_errors=ns.retry_errors, secrets=secrets, planner=planner if planner.enabled else None)
    print(json.dumps(result["summary"]))
    return 0 if result.get("complete") else 2


def wants_breadth(args: list[str]) -> bool:
    """True for `run|selftest|rescore ... --suite FILE` where FILE is a breadth suite."""
    if not args or args[0] not in ("run", "selftest", "rescore"):
        return False
    for i, a in enumerate(args):
        value = args[i + 1] if a == "--suite" and i + 1 < len(args) else a[8:] if a.startswith("--suite=") else None
        if value:
            return bool(suite_kind(Path(value)))
    return False


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
