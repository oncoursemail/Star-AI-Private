"""Opt-in trusted Windows launcher for disposable *optional* VTuber AI workers.

This is the missing launch-side counterpart to the GPU lease ledger and the
host-owned stop adapter. All launch specifications come from a fixed local
owner-configured registry, never generated by an LLM, viewer, Discord command,
or network request. This module is NOT a sandbox, production model manager,
game-input interface, or streaming/broadcast controller.

A host must explicitly enable the ledger, feed verified fresh telemetry, and
enable this supervisor before it can launch. Core llama-server, OBS, gameplay,
avatar and audio services must NEVER be enrolled as disposable workers.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import platform
import re
import subprocess
from threading import RLock
from typing import Callable

from .stream_gpu_owned_worker_host import HostOwnedOptionalGPUWorkers, OwnedWorkerTick
from .stream_host_artifact_pins import HostArtifactPin, MAX_LAUNCH_HASH_BYTES
from .stream_windows_job_worker import WindowsJobWorker, spawn_windows_job
from .stream_realtime_gpu_leases import RealtimeGPUWorkLeases, WorkLeaseTicket, _now

_ALIAS = re.compile(r"[A-Za-z][A-Za-z0-9_.-]{0,63}\Z")
_OPTIONAL = frozenset({"vision", "research", "training", "render"})


@dataclass(frozen=True, eq=False)
class HostOptionalWorkerPlan:
    """Immutable host-selected process recipe; identity matters, not labels.

    The executable, arguments and working directory are checked at plan
    construction and rechecked at every launch to fail closed on path swaps.
    Owner policy must also independently verify trusted binary/weight digests.
    """

    alias: str
    kind: str
    vram_mib: int
    executable: Path
    arguments: tuple[str, ...] = ()
    working_directory: Path | None = None
    executable_pin: HostArtifactPin | None = None
    additional_pins: tuple[HostArtifactPin, ...] = ()

    def __post_init__(self) -> None:
        if type(self.alias) is not str or not _ALIAS.fullmatch(self.alias):
            raise ValueError("invalid host-owned plan alias")
        if type(self.kind) is not str or self.kind not in _OPTIONAL:
            raise ValueError("cannot manage critical game, voice or OBS processes")
        if type(self.vram_mib) is not int or not 1 <= self.vram_mib <= 32768:
            raise ValueError("invalid bounded optional GPU reservation")
        if not isinstance(self.executable, Path) or not self.executable.is_absolute():
            raise ValueError("absolute Windows executable path required")
        if self.executable.suffix.lower() != ".exe" or self.executable.is_symlink():
            raise ValueError("only a fixed non-symlink executable may run")
        if not self.executable.is_file():
            raise ValueError("host-selected executable is missing")
        if type(self.arguments) is not tuple or len(self.arguments) > 48:
            raise ValueError("host arguments must be an immutable bounded tuple")
        for argument in self.arguments:
            if (type(argument) is not str or len(argument) > 4096
                    or "\x00" in argument or any(ord(c) < 32 for c in argument)):
                raise ValueError("invalid fixed host argument")
        if self.executable_pin is not None and (
            type(self.executable_pin) is not HostArtifactPin
            or self.executable_pin.path != self.executable
        ):
            raise ValueError("executable pin must match the selected binary")
        if (type(self.additional_pins) is not tuple
                or len(self.additional_pins) > 8
                or any(type(pin) is not HostArtifactPin for pin in self.additional_pins)
                or len({pin.path for pin in self.additional_pins}) != len(self.additional_pins)
                or any(pin.path == self.executable for pin in self.additional_pins)):
            raise ValueError("additional launch pins must be unique local files")
        if self.working_directory is not None:
            directory = self.working_directory
            if (not isinstance(directory, Path) or not directory.is_absolute()
                    or directory.is_symlink() or not directory.is_dir()):
                raise ValueError("host working directory must exist and be absolute")

    def verified_command(
        self, *, require_artifact_pins: bool = False
    ) -> tuple[list[str], str | None]:
        """Revalidate fixed files, not caller-provided runtime arguments."""
        if self.executable.is_symlink() or not self.executable.is_file():
            raise ValueError("owner-selected executable changed or disappeared")
        if require_artifact_pins and self.executable_pin is None:
            raise ValueError("strict launch requires a pinned binary")
        remaining_bytes = MAX_LAUNCH_HASH_BYTES
        for pin in (self.executable_pin, *self.additional_pins):
            if pin is None:
                continue
            try:
                size = pin.path.stat().st_size
            except OSError as exc:
                raise ValueError("trusted launch artifact unavailable") from exc
            if size > remaining_bytes or not pin.verify(max_bytes=max(1, remaining_bytes)):
                raise ValueError("trusted launch artifact changed or is too large")
            remaining_bytes -= size
        directory = self.working_directory
        if directory is not None and (directory.is_symlink() or not directory.is_dir()):
            raise ValueError("owner-selected working directory changed")
        return [str(self.executable), *self.arguments], (
            str(directory) if directory is not None else None
        )


@dataclass(frozen=True)
class OptionalWorkerLaunchResult:
    """Anonymous accounting result, never a raw command or OS PID."""

    outcome: str
    reason: str
    active_reservations: int
    authorizes_execution: bool = False
    authorizes_gameplay: bool = False
    authorizes_broadcast: bool = False


def _spawn_windows(argv: list[str], cwd: str | None) -> subprocess.Popen[bytes]:
    """Only the fixed Windows command, without shell, PATH lookup or pipes."""
    return subprocess.Popen(
        argv, cwd=cwd, shell=False, stdin=subprocess.DEVNULL,
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        close_fds=True, creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
    )


class HostOptionalGPUWorkerLaunchSupervisor:
    """Host-only opt-in bridge from vetted plans to reserved Windows processes.

    Launched process handles pass directly to HostOwnedOptionalGPUWorkers.
    Admission is advisory until this host executes the launch; a launch error
    leaves the claim charged and disables the session rather than guessing
    whether Windows created a process. This conservative state requires
    operator reconciliation before restarting the GPU admission session.
    """

    def __init__(
        self,
        leases: RealtimeGPUWorkLeases,
        workers: HostOwnedOptionalGPUWorkers,
        plans: tuple[HostOptionalWorkerPlan, ...],
        *,
        system_name: Callable[[], str] = platform.system,
        spawn: Callable[[list[str], str | None], subprocess.Popen[bytes]] = _spawn_windows,
        require_job_tree: bool = False,
        require_artifact_pins: bool = False,
        job_spawn: Callable[..., WindowsJobWorker] = spawn_windows_job,
    ) -> None:
        if not isinstance(leases, RealtimeGPUWorkLeases) or workers._leases is not leases:
            raise TypeError("launch supervisor needs one trusted host lease session")
        if (type(plans) is not tuple or not plans
                or any(type(x) is not HostOptionalWorkerPlan for x in plans)):
            raise TypeError("a nonempty immutable owner-configured plan registry is required")
        if len({plan.alias for plan in plans}) != len(plans):
            raise ValueError("duplicate host plan")
        if (type(require_job_tree) is not bool
                or type(require_artifact_pins) is not bool or not callable(job_spawn)):
            raise TypeError("explicit host-owned Windows job policy required")
        if not callable(system_name) or not callable(spawn):
            raise TypeError("trusted local OS and process factories required")
        self._leases = leases
        self._workers = workers
        self._plans = plans
        self._system_name = system_name
        self._spawn = spawn
        self._job_spawn = job_spawn
        self._require_job_tree = require_job_tree
        self._require_pins = require_artifact_pins
        self._lock = RLock()
        self._enabled = False
        self._faulted = False
        self._active_plans: dict[str, WorkLeaseTicket] = {}

    def enable(self, *, owner_approved: bool = False) -> None:
        if owner_approved is not True:
            raise PermissionError("owner must explicitly enable optional Windows launches")
        with self._lock:
            if self._faulted:
                raise RuntimeError("failed launch needs independent host reconciliation")
            if self._enabled:
                raise RuntimeError("optional launch session already enabled")
            if self._system_name() != "Windows":
                raise RuntimeError("optional worker launching is Windows only")
            if not self._leases.metrics()["enabled"]:
                raise RuntimeError("host GPU admission ledger must already be enabled")
            self._workers.enable(owner_approved=True)
            self._enabled = True

    def launch(
        self, plan: HostOptionalWorkerPlan, *, now_ms: float,
        owner_approved: bool = False,
    ) -> OptionalWorkerLaunchResult:
        now = _now(now_ms)
        if owner_approved is not True:
            raise PermissionError("host-owned optional launch approval required")
        with self._lock:
            if not self._enabled or self._faulted or self._system_name() != "Windows":
                return self._result("deferred", "optional_launch_disabled")
            if not any(plan is item for item in self._plans):
                raise PermissionError("unregistered plan object is not launch authority")
            previous = self._active_plans.get(plan.alias)
            if previous is not None and self._leases._lookup(previous) is not None:
                return self._result("deferred", "optional_plan_worker_already_outstanding")
            self._active_plans.pop(plan.alias, None)
            try:
                argv, cwd = plan.verified_command(
                    require_artifact_pins=self._require_pins,
                )
            except (OSError, ValueError):
                return self._result("deferred", "trusted_launch_files_invalid")
            advice = self._leases.reserve(
                kind=plan.kind, vram_mib=plan.vram_mib,
                now_ms=now, host_verified=True,
            )
            ticket = advice.ticket
            if ticket is None:
                return self._result("deferred", advice.reason)
            self._active_plans[plan.alias] = ticket
            # A reserved lease is not permission to bypass changing host
            # pressure. A tick later must stop the worker if it changes.
            try:
                if self._require_job_tree and self._require_pins:
                    # A Job-bound process begins suspended. Recheck ALL pinned
                    # files immediately before its main thread resumes. This
                    # is a trusted callback invoked INSIDE the Win32 launcher,
                    # not a model-supplied hook. Repeated hashing is bounded.
                    def verify_before_resume() -> bool:
                        return plan.verified_command(require_artifact_pins=True) == (argv, cwd)

                    process = self._job_spawn(
                        argv, cwd, pre_resume=verify_before_resume,
                    )
                elif self._require_job_tree:
                    process = self._job_spawn(argv, cwd)
                else:
                    process = self._spawn(argv, cwd)
                if self._require_job_tree:
                    if not isinstance(process, WindowsJobWorker):
                        raise TypeError("host must return original Windows Job worker")
                elif not isinstance(process, subprocess.Popen):
                    raise TypeError("trusted launch factory returned no original Popen")
            except Exception:
                self._faulted = True
                self._enabled = False
                self._workers.disable()
                # A failed Windows process creation can be ambiguous: NEVER
                # release a GPU claim without independent OS exit evidence.
                return self._result("fault", "launch_uncertain_claim_retained")
            try:
                bound = self._workers.enroll_spawned(
                    ticket, process, now_ms=now, owner_approved=True,
                )
            except Exception:
                self._faulted = True
                self._enabled = False
                self._workers.disable()
                # Original host-owned process handle, never a looked-up PID.
                try:
                    if isinstance(process, WindowsJobWorker) or process.poll() is None:
                        process.terminate()
                except Exception:
                    pass
                return self._result("fault", "worker_enrollment_uncertain")
            if not bound:
                # The host adapter quarantines the original process and will
                # request a stop. Reconcile now rather than letting it idle.
                self._workers.tick(now_ms=now)
                return self._result("quarantined", "worker_not_independently_pinned")
            return self._result("started", "host_owned_optional_worker_started")

    def _result(self, outcome: str, reason: str) -> OptionalWorkerLaunchResult:
        return OptionalWorkerLaunchResult(
            outcome, reason, self._leases.metrics()["outstanding_claims"],
        )

    def tick(self, *, now_ms: float) -> OwnedWorkerTick:
        """Call on a trusted supervisor thread, never gameplay/audio threads."""
        with self._lock:
            result = self._workers.tick(now_ms=_now(now_ms))
            for alias, ticket in tuple(self._active_plans.items()):
                if self._leases._lookup(ticket) is None:
                    del self._active_plans[alias]
        return result

    def disable(self) -> None:
        with self._lock:
            self._enabled = False
            self._workers.disable()

    def metrics(self) -> dict[str, int | bool]:
        with self._lock:
            return {
                "enabled": self._enabled,
                "faulted": self._faulted,
                "configured_optional_plans": len(self._plans),
                "job_tree_containment_required": self._require_job_tree,
                "artifact_pins_required": self._require_pins,
                "outstanding_reservations": self._leases.metrics()["outstanding_claims"],
                "owned_workers": self._workers.metrics()["owned_workers"],
            }


