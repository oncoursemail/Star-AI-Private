"""Evidence-first human-quality acceptance and bounded repair previews for STAR.

Not a new model, subjective aesthetic judge, security permission, CI replacement
or producer of proof. Trusted host integrations supply real test/owner receipts.
Agent-written claims and simulated fixtures cannot certify a native deliverable.
No work runs and no local file is edited by this module.
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass
import hashlib
import json
from pathlib import Path
import re
from typing import Mapping

_SHA = re.compile(r"[0-9a-f]{64}\Z")
_ID = re.compile(r"[A-Za-z][A-Za-z0-9_.-]{1,79}\Z")
KINDS = frozenset({
    "unit_test", "integration_test", "native_playtest", "visual_capture",
    "human_review", "audio_identification", "source_check",
    "performance_profile", "security_check", "accessibility_check",
})
VALID_OUTCOMES = frozenset({"pass", "fail", "inconclusive"})
MAX_REQUIREMENTS, MAX_RECEIPTS, MAX_ATTEMPTS = 32, 128, 3


def _id(value: object) -> bool:
    return isinstance(value, str) and bool(_ID.fullmatch(value))


def _sha(value: object) -> bool:
    return isinstance(value, str) and bool(_SHA.fullmatch(value))


@dataclass(frozen=True)
class Criterion:
    """An owner-specified deliverable requirement; not generated by a judge."""
    id: str
    category: str
    accepted_kinds: tuple[str, ...]
    critical: bool = True
    require_native: bool = False
    require_owner_review: bool = False
    min_independent: int = 1

    def __post_init__(self) -> None:
        if not _id(self.id) or not _id(self.category):
            raise ValueError("Invalid criterion identifier/category")
        if (type(self.accepted_kinds) is not tuple or not self.accepted_kinds
                or len(self.accepted_kinds) != len(set(self.accepted_kinds))
                or not set(self.accepted_kinds) <= KINDS):
            raise ValueError("Criterion needs distinct supported evidence kinds")
        if type(self.critical) is not bool or type(self.require_native) is not bool or type(self.require_owner_review) is not bool:
            raise ValueError("Criterion check flags must be explicit booleans")
        if type(self.min_independent) is not int or not 1 <= self.min_independent <= 3:
            raise ValueError("Independent evidence count must be 1..3")
        if self.require_native and not set(self.accepted_kinds) & {
            "native_playtest", "visual_capture", "audio_identification", "performance_profile", "accessibility_check"
        }:
            raise ValueError("Native-only criterion has no native-capable evidence kind")


@dataclass(frozen=True)
class CheckReceipt:
    """Receipt from independent trusted harness or authenticated owner surface.

    A hash binds an artifact/revision and a *real* evidence object; a hash does
    not independently prove the evidence was genuine. The host must attest it.
    """
    criterion_id: str
    artifact_sha256: str
    evidence_sha256: str
    kind: str
    outcome: str
    origin: str
    environment: str
    detail: str = ""

    def __post_init__(self) -> None:
        if not _id(self.criterion_id) or not _sha(self.artifact_sha256) or not _sha(self.evidence_sha256):
            raise ValueError("A receipt needs valid criterion and content hashes")
        if self.kind not in KINDS or self.outcome not in VALID_OUTCOMES:
            raise ValueError("Unsupported evidence kind/outcome")
        if self.origin not in {"trusted_host", "owner", "agent", "synthetic"}:
            raise ValueError("Unsupported receipt origin")
        if self.environment not in {"native", "static", "simulation"}:
            raise ValueError("Unsupported evidence environment")
        if not isinstance(self.detail, str) or len(self.detail) > 300:
            raise ValueError("Receipt explanation exceeds the limit")
        if self.kind == "human_review" and self.origin != "owner":
            raise ValueError("Only the authenticated owner may submit human review")
        if self.origin == "owner" and self.kind != "human_review":
            raise ValueError("Owner approvals use the human_review evidence kind")


def template(name: str) -> tuple[Criterion, ...]:
    """Deterministic default rubric; users or trusted host may add requirements.

    Static tests are quick; native evidence and owner signoff are separate.
    """
    def c(cid: str, kinds: tuple[str, ...], *, native=False, owner=False, critical=True):
        return Criterion(cid, name, kinds, critical, native, owner)
    suites = {
        "software": (
            c("requirements", ("unit_test", "integration_test")),
            c("real_execution", ("integration_test", "native_playtest")),
            c("security", ("security_check",)),
            c("performance", ("performance_profile",), native=True, critical=False),
        ),
        "interface": (
            c("functional", ("integration_test", "native_playtest")),
            c("visual_states", ("visual_capture",), native=True),
            c("accessibility", ("accessibility_check",), native=True),
            c("human_design_review", ("visual_capture",), native=True, owner=True),
        ),
        "animation": (
            c("clip_structure", ("unit_test", "integration_test")),
            c("native_motion", ("native_playtest",), native=True),
            c("frame_evidence", ("visual_capture",), native=True),
            c("owner_motion_quality", ("visual_capture",), native=True, owner=True),
        ),
        "research": (
            c("source_grounding", ("source_check",)),
            c("factual_check", ("source_check", "integration_test")),
            c("owner_requirements", ("human_review",), owner=True, critical=False),
        ),
        "music": (
            c("source_fingerprint", ("audio_identification",), native=True),
            c("rights_and_consent", ("security_check",)),
            c("recording_review", ("audio_identification",), native=True, owner=True),
        ),
        "game": (
            c("unit_and_logic", ("unit_test", "integration_test")),
            c("live_multiplayer", ("native_playtest",), native=True),
            c("visual_motion", ("visual_capture",), native=True),
            c("runtime_profile", ("performance_profile",), native=True),
            c("human_gameplay", ("native_playtest",), native=True, owner=True),
            c("server_security", ("security_check",)),
        ),
    }
    if name not in suites:
        raise ValueError("Unknown human-quality rubric")
    return suites[name]


def review(artifact_sha256: str, criteria: tuple[Criterion, ...],
           receipts: tuple[CheckReceipt, ...] = (),
           *, repair_attempts: Mapping[str, int] | None = None,
           owner_approved_learning: bool = False) -> dict:
    """Advisory, fail-closed readiness report with finite targeted next actions.

    Authenticated host must supply and verify receipt provenance and evidence
    blobs; models never gain authority by creating matching JSON fields.
    """
    if not _sha(artifact_sha256):
        raise ValueError("Artifact SHA-256 required")
    if (type(criteria) is not tuple or not 1 <= len(criteria) <= MAX_REQUIREMENTS
            or any(type(item) is not Criterion for item in criteria)
            or len({c.id for c in criteria}) != len(criteria)):
        raise ValueError("Provide 1..32 unique trusted quality requirements")
    if type(receipts) is not tuple or len(receipts) > MAX_RECEIPTS or any(type(x) is not CheckReceipt for x in receipts):
        raise ValueError("Provide up to 128 bounded check receipts")
    if type(owner_approved_learning) is not bool:
        raise ValueError("Explicit owner learning authorization required")
    if any(receipt.criterion_id not in {c.id for c in criteria} for receipt in receipts):
        raise ValueError("Unknown criterion in check receipts")
    attempts = dict(repair_attempts or {})
    if set(attempts) - {c.id for c in criteria} or any(
        type(value) is not int or value < 0 or value > MAX_ATTEMPTS for value in attempts.values()
    ):
        raise ValueError("Only 0..3 bounded repair attempts per criterion")
    results = []
    for criterion in criteria:
        observed = [item for item in receipts
                    if item.criterion_id == criterion.id
                    and item.artifact_sha256 == artifact_sha256
                    and item.origin in {"trusted_host", "owner"}
                    and item.kind in criterion.accepted_kinds
                    and (not criterion.require_native or item.environment == "native")]
        # A human approval is separately required; test output cannot impersonate a human.
        owner_receipts = [item for item in receipts
                          if item.criterion_id == criterion.id
                          and item.artifact_sha256 == artifact_sha256
                          and item.kind == "human_review" and item.origin == "owner"]
        failed = any(item.outcome == "fail" for item in observed + owner_receipts)
        unique = {(item.kind, item.evidence_sha256): item for item in observed if item.outcome == "pass"}
        passes = len(unique)
        human_pass = any(item.outcome == "pass" for item in owner_receipts)
        if failed:
            state = "failed"
        elif passes < criterion.min_independent:
            state = "needs_evidence"
        elif criterion.require_owner_review and not human_pass:
            state = "needs_owner"
        else:
            state = "passed"
        results.append({
            "id": criterion.id, "category": criterion.category, "critical": criterion.critical,
            "state": state, "independent_passes": passes,
            "required_passes": criterion.min_independent, "owner_review_passed": human_pass,
            "repair_attempts": attempts.get(criterion.id, 0),
        })
    blockers = [row for row in results if row["critical"] and row["state"] != "passed"]
    if any(row["state"] == "failed" for row in blockers):
        status = "blocked"
    elif any(row["state"] == "needs_evidence" for row in blockers):
        status = "needs_evidence"
    elif any(row["state"] == "needs_owner" for row in blockers):
        status = "needs_owner"
    else:
        status = "qualified" if all(x["state"] == "passed" for x in results) else "qualified_with_advisories"
    actions = []
    for row in sorted(results, key=lambda x: (not x["critical"], x["state"] != "failed", x["id"])):
        if row["state"] == "passed":
            continue
        attempts_used = row["repair_attempts"]
        if row["state"] == "failed":
            verb = "escalate_to_owner" if attempts_used >= MAX_ATTEMPTS else "repair_then_retest"
        elif row["state"] == "needs_owner":
            verb = "request_owner_review"
        else:
            verb = "run_independent_evidence_check"
        actions.append({"criterion_id": row["id"], "action": verb,
                        "next_attempt": attempts_used + 1 if verb == "repair_then_retest" else None})
    evidence_digest = hashlib.sha256(json.dumps(
        [{"id": r.criterion_id, "sha": r.evidence_sha256, "status": r.outcome, "kind": r.kind}
         for r in sorted(receipts, key=lambda item: (item.criterion_id, item.evidence_sha256))],
        sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    return {
        "artifact_sha256": artifact_sha256, "state": status, "checks_total": len(criteria),
        "checks_passed": sum(r["state"] == "passed" for r in results),
        "checks_failed": sum(r["state"] == "failed" for r in results),
        "criteria": results, "next_actions": actions[:8],
        "evidence_index_sha256": evidence_digest,
        "eligible_for_learning_proposal": status == "qualified" and owner_approved_learning,
        "model_quality_proven": False,
        "note": "Receipt content and owner identity must be validated by the trusted host. Even a qualified checklist is not proof of perfection or human-level intelligence.",
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Offline STAR human-quality readiness preview")
    parser.add_argument("--template", choices=("software", "interface", "animation", "research", "music", "game"))
    parser.add_argument("--manifest", type=Path, help="Local host-generated JSON with artifact_sha256 and checks")
    args = parser.parse_args(argv)
    if not args.template and not args.manifest:
        parser.error("Provide --template or --manifest")
    if args.template and not args.manifest:
        print(json.dumps([c.__dict__ for c in template(args.template)], indent=2))
        return 0
    try:
        if args.manifest is None or args.manifest.stat().st_size > 128_000:
            raise ValueError("Missing or overlarge quality manifest")
        value = json.loads(args.manifest.read_text(encoding="utf-8"))
        if not isinstance(value, dict):
            raise ValueError("Quality manifest must be an object")
        criteria = template(args.template) if args.template else tuple(Criterion(**x) for x in value["criteria"])
        receipts = tuple(CheckReceipt(**x) for x in value.get("receipts", []))
        output = review(value["artifact_sha256"], criteria, receipts,
                        repair_attempts=value.get("repair_attempts"),
                        owner_approved_learning=False)  # CLI cannot authorize learning.
    except (OSError, ValueError, KeyError, TypeError) as exc:
        parser.error(str(exc))
    print(json.dumps(output, indent=2))
    return 0 if output["state"] == "qualified" else 1


if __name__ == "__main__":
    raise SystemExit(main())
