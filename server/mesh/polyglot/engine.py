# ------------------------------------------------------------------------------------------------ luacheck std
def _lua_table(v) -> str:
    if isinstance(v, dict):
        items = []
        for k, x in v.items():
            if isinstance(k, int):
                items.append(_lua_table(x))
            else:
                items.append(f'["{k}"] = {_lua_table(x)}')
        return "{" + ", ".join(items) + "}"
    if isinstance(v, (list, tuple)):
        return "{" + ", ".join(_lua_table(x) for x in v) + "}"
    if isinstance(v, bool):
        return "true" if v else "false"
    return '"' + str(v).replace('"', "") + '"'


LIBS = ("string", "table", "math", "io", "os", "utf8", "coroutine", "debug", "package", "bit", "jit")
_STD: dict = {}


def _lib_fields(names: list[str]) -> dict:
    return {"fields": {n: {} for n in names}}


def luacheck_std(kind: str) -> str:
    """The text of a .luacheckrc for plain Lua 5.4 ("lua") or LOVE 11 / LuaJIT ("love")."""
    if kind in _STD:
        return _STD[kind]
    read: dict = {}
    if kind == "lua":
        d = data("lua54_std.json")
        for lib in LIBS:
            if d.get(lib):
                read[lib] = _lib_fields(d[lib])
        for n in d.get("_G", []):
            read.setdefault(n, {})
        read["arg"] = {}
    else:
        d, ld = data("love_std.json"), data("love_std.json").get("love", {})
        for lib, names in d.get("lj", {}).items():
            if lib == "_G":
                for n in names:
                    read.setdefault(n, {})
            else:
                read[lib] = _lib_fields(names)
        love_fields = {m: _lib_fields(names) for m, names in ld.items() if m != "_top"}
        love_fields.update({n: {} for n in ld.get("_top", [])})
        read["love"] = {"fields": love_fields}
        read.setdefault("arg", {})
    text = "std = {globals = {}, read_globals = " + _lua_table(read) + "}\n"
    _STD[kind] = text
    return text


