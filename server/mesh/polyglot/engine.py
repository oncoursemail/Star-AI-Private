W_LINE = re.compile(r"^main\.lua:(\d+):\d+: \((W|E)(\d+)\) (.*)$", re.M)


def _close(name: str, names, cutoff: float = 0.75) -> str | None:
    hits = difflib.get_close_matches(name, list(names), n=1, cutoff=cutoff)
    return hits[0] if hits else None


def _strip(code: str) -> str:
    """The code without comments and string contents (offsets kept)."""
    def blank(m):
        return re.sub(r"[^\n]", " ", m.group(0))
    code = re.sub(r"--\[(=*)\[.*?\]\1\]", blank, code, flags=re.S)
    code = re.sub(r"--[^\n]*", blank, code)
    code = re.sub(r"\[(=*)\[.*?\]\1\]", blank, code, flags=re.S)
    return re.sub(r"\"(?:\\.|[^\"\\\n])*\"|'(?:\\.|[^'\\\n])*'", blank, code)


def _assigned(code: str, context: str) -> set[str]:
    """Names (and a.b fields) the answer assigns itself: they exist for the rest of the answer."""
    out = set()
    text = code + "\n" + (context or "")
    for m in re.finditer(r"\bfunction\s+([A-Za-z_][\w]*(?:[.:][A-Za-z_]\w*)*)", text):
        out.add(m.group(1).replace(":", "."))
    for m in re.finditer(r"(?<![\w.])([A-Za-z_]\w*(?:\.[A-Za-z_]\w*)?)\s*=(?!=)", text):
        out.add(m.group(1))
    return out


def check_luacheck(code: str, context: str, kind: str, src: str | None = None) -> list[dict]:
    """Syntax errors, undefined globals and undefined library fields (kind "lua" = Lua 5.4, "love" = LuaJIT + love.*)."""
    label = "Lua 5.4" if kind == "lua" else "LOVE 11 (LuaJIT)"
    with R["Workdir"](files={"main.lua": src if src is not None else R["blank_ellipsis"](code, "--"),
                             ".luacheckrc": luacheck_std(kind)}) as d:
        r = R["run_limited"](["luacheck", "--only", "011", "113", "143", "111", "--codes", "--formatter=plain",
                              "--no-color", "--config", ".luacheckrc", "main.lua"], d)
    mine = _assigned(code, context)
    set_here = {m.group(1) for m in re.finditer(r"setting non-standard global variable '(\w+)'", r["stdout"])}
    probs, seen = [], set()
    for m in W_LINE.finditer(r["stdout"]):
        line, typ, num, msg = int(m.group(1)), m.group(2), m.group(3), m.group(4)
        if typ == "E":
            probs.append(problem("syntax", f"{label}: {msg}", line))
            continue
        if num == "113":
            name = re.search(r"'([^']+)'", msg).group(1)
            if name in set_here or name in mine or R["elsewhere"](name, code, context) and name not in ROBLOX:
                continue
            key = ("v", name)
            if key in seen:
                continue
            seen.add(key)
            if name in ROBLOX:
                probs.append(problem("api", f"{label}: '{name}' is a Roblox/Luau global; it does not exist here "
                                            f"(runtime error: attempt to index/call a nil value)", line, name=name,
                                     suggestion=SUGG.get(name)))
            else:
                std = data("lua54_std.json") if kind == "lua" else data("love_std.json").get("lj", {})
                names = sorted(set(std.get("_G", [])) | {n for n in LIBS if n in std})
                p = problem("api", f"{label}: undefined variable '{name}' (not a standard global, not defined in the "
                                   f"code)", line, name=name, suggestion=SUGG.get(name) or _close(name, names))
                probs.append(p)
        elif num == "143":
            m2 = re.search(r"undefined field '([^']+)' of (?:global )?'([^']+)'", msg)
            if not m2:
                continue
            full = f"{m2.group(2)}.{m2.group(1)}"      # luacheck: field 'graphics.setColour' of global 'love'
            owner, _, field = full.rpartition(".")
            if full in mine:
                continue
            if (full, "f") in seen:
                continue
            seen.add((full, "f"))
            lib = owner.split(".")[-1]
            if owner.startswith("love."):
                fields = data("love_std.json").get("love", {}).get(owner.split(".")[1], [])
            elif kind == "lua":
                fields = data("lua54_std.json").get(lib, [])
            else:
                fields = data("love_std.json").get("lj", {}).get(lib, [])
            sugg = SUGG.get(full) or (R["closest"](field, fields) if fields else None)
            p = problem("api", f"{label}: {full} does not exist" + (" (Roblox/Luau or another language's function)"
                        if kind == "lua" and owner in ("string", "table", "math", "os", "io") else ""), line, name=full,
                        suggestion=sugg)
            if fields:
                p["candidates"] = difflib.get_close_matches(field, fields, n=8, cutoff=0.4)
            probs.append(p)
    clean = _strip(code)
    probs += _format_int_rule(code)
    probs += check_lua_pitfalls(code, label)
    if kind == "lua":
        for m in re.finditer(r"[:.](" + "|".join(LUA_BAD_METHODS) + r")\s*\(", clean):
            name = m.group(1)
            if re.search(r"function\s+[\w.:]*[.:]" + name + r"\b|\." + name + r"\s*=", clean):
                continue                                    # the answer defines it itself
            if f"string.{name}" in mine:
                continue
            sug = SUGG.get(f"string.{name}")
            probs.append(problem("api", f"{label}: strings have no :{name}() method (only the string library: "
                                        f"{', '.join(sorted(data('lua54_std.json').get('string', [])))})",
                                 clean.count("\n", 0, m.start()) + 1, name=f"string.{name}", suggestion=sug))
            break
    return probs


INT_CONV_ALL = re.compile(r"%[-+ #0]*\d*(?:\.\d+)?([a-zA-Z%])")
FLOATY = re.compile(r"(?<![/])/(?![/])|\^|\bmath\.(?:sqrt|exp|log|sin|cos|tan|pow|fmod)\b|\d\.\d")


def _format_int_rule(code: str) -> list[dict]:
    """string.format("%d", x / 2): a float without an integer value is a runtime error in Lua 5.3+."""
    probs = []
    text = _strip(code)
    for m in re.finditer(r"string\.format\s*\(", text):
        i = m.end()
        depth, j = 1, i
        while j < len(text) and depth:
            depth += text[j] == "("
            depth -= text[j] == ")"
            j += 1
        args = _split_commas(code[i:j - 1])
        if not args or args[0].strip()[:1] not in ("'", '"'):
            continue
        convs = [c for c in INT_CONV_ALL.findall(args[0]) if c != "%"]
        for k, c in enumerate(convs):
            if c not in "diuxXoc" or k + 1 >= len(args):
                continue
            arg = args[k + 1]
            if FLOATY.search(_strip(arg)) and not re.search(r"math\.(?:floor|ceil|tointeger)|//", arg):
                probs.append(problem("api", f"Lua 5.4: string.format('%{c}') needs an integer, but {arg.strip()[:40]} is a float "
                                            f"and errors when it has no integer value",
                                     text.count("\n", 0, m.start()) + 1, severity="warning", name="string.format",
                                     suggestion="use // (floor division), math.floor(...), math.tointeger(...) or %.0f"))
                break
    return probs


READ_FORMATS = re.compile(r"""\b(?:io\.read|\w+:read|io\.stdin:read)\s*\(([^)]*)\)""")
MATCH_ASSIGN = re.compile(r"\blocal\s+(\w+)\s*=\s*(?:[\w.]+|\([^()]*\))?[:.]\s*(?:match|gmatch|find)\s*\(|"
                          r"\blocal\s+(\w+)\s*=\s*string\.(?:match|find)\s*\(")
BIG_INT = re.compile(r"(?<![\w.])(\d{19,})(?![\w.])")


def check_lua_pitfalls(code: str, label: str) -> list[dict]:
    """Runtime errors that plain Lua / LuaJIT programs of a model typically contain and a parser cannot see."""
    clean = _strip(code)
    probs: list[dict] = []

    def line_of(pos: int) -> int:
        return clean.count("\n", 0, pos) + 1

    for m in re.finditer(r"ipairs\s*\(\s*io\.lines\b", clean):
        if not any(p["name"] == "io.lines" for p in probs):
            probs.append(problem("api", f"{label}: ipairs(io.lines) / ipairs(io.lines()) errors: io.lines() returns an iterator "
                                        f"function, not a table; write `for line in io.lines() do ... end`", line_of(m.start()),
                                 name="io.lines", suggestion="for line in io.lines() do"))
    for m in re.finditer(r"\bin\s+io\.lines\s+do", clean):
        probs.append(problem("api", f"{label}: `for line in io.lines do` iterates the function itself; call it: "
                                    f"`for line in io.lines() do`", line_of(m.start()), name="io.lines",
                             suggestion="for line in io.lines() do"))
        break
    for m in READ_FORMATS.finditer(code):
        for fmt in re.findall(r"""["']([^"']*)["']""", m.group(1)):
            body = fmt[1:] if fmt.startswith("*") else fmt
            if not body or body[0] not in "nlaL":
                probs.append(problem("api", f"{label}: io.read format '{fmt}' is invalid (error: bad argument #1 to 'read'); "
                                            f"the formats are \"n\" (number), \"l\" (line), \"L\" (line with newline), \"a\" (all) "
                                            f"or a byte count", code.count("\n", 0, m.start()) + 1, name="io.read",
                                     suggestion='io.read("l")'))
                break
    seen = set()
    for m in MATCH_ASSIGN.finditer(clean):
        var = m.group(1) or m.group(2)
        if var in seen:
            continue
        # one value is stored: the first capture (or the start index); indexing it like a table fails at runtime
        use = re.search(r"(?<![\w.])" + re.escape(var) + r"\s*\[\s*\d+\s*\]", clean[m.end():])
        if use and not re.search(r"\b" + re.escape(var) + r"\s*=\s*[^=\n]*[{]", clean[m.end():m.end() + use.start()]):
            seen.add(var)
            probs.append(problem("api", f"{label}: `{var}` holds only the FIRST capture of match/find (a string or number), so "
                                        f"`{var}[1]` is nil: string.match returns the captures as separate values",
                                 line_of(m.start()),
                                 name=var, suggestion="local a, b = s:match(pattern)   (one variable per capture)"))
    for m in BIG_INT.finditer(clean):
        if int(m.group(1)) > 9223372036854775807:
            probs.append(problem("api", f"{label}: the integer literal {m.group(1)[:24]} does not fit in 64 bits, so Lua reads it as "
                                        f"a float (inexact, and `%d`/bit operators then fail); write it as a hexadecimal literal "
                                        f"such as 0xcbf29ce484222325 (hex literals wrap around to a 64-bit integer)",
                                 line_of(m.start()), severity="warning", name=m.group(1)[:24],
                                 suggestion="a hexadecimal literal (0x...)"))
            break
    return probs


