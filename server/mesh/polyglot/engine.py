def _split_args(s: str) -> list[str]:
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "(<[{":
            depth += 1
        elif ch in ")>]}":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def _ptype(param: str) -> str:
    """The type of a parameter declaration without its name and default value, spaces removed."""
    p = re.sub(r"=.*$", "", param.strip())
    m = re.match(r"^(.*?)(?:\s+|(?<=[*&]))([A-Za-z_]\w*)$", p)
    if m and m.group(1).strip() and m.group(1).strip() not in ("const", "unsigned", "struct", "class"):
        p = m.group(1)
    return re.sub(r"\s+", "", p)


def _find_body(text: str, start: int) -> str:
    i = text.find("{", start)
    if i < 0:
        return ""
    depth, j = 0, i
    while j < len(text):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[i:j + 1]
        j += 1
    return text[i:]


def _blank_comments(text: str) -> str:
    return re.sub(r"//[^\n]*|/\*.*?\*/", lambda m: re.sub(r"[^\n]", " ", m.group(0)), text, flags=re.S)


