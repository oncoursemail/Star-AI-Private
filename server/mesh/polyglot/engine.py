KEYSET: set = set()


def _keys() -> set:
    if not KEYSET:
        d = data("love_std.json")
        KEYSET.update(d.get("keys", []))
    return KEYSET


OLD_KEYS = {"enter": "return", "spacebar": "space", "esc": "escape", "ctrl": "lctrl", "shift": "lshift", "alt": "lalt",
            "del": "delete", "ret": "return", " ": "space", "Space": "space", "Return": "return", "Escape": "escape"}
COLOR_FN = re.compile(r"love\.graphics\.(setColor|setBackgroundColor|clear)\s*\(([^()]*(?:\([^()]*\)[^()]*)*)\)")
NUM_ONLY = re.compile(r"^-?\d+(?:\.\d+)?$")


def _split_commas(s: str) -> list[str]:
    """Split on top-level commas (outside brackets and quoted strings)."""
    out, depth, cur, quote, esc = [], 0, "", "", False
    for ch in s:
        if quote:
            cur += ch
            if esc:
                esc = False
            elif ch == chr(92):
                esc = True
            elif ch == quote:
                quote = ""
            continue
        if ch in ("'", '"'):
            quote = ch
        depth += ch in "([{"
        depth -= ch in ")]}"
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    return out + [cur] if cur.strip() else out



def check_love_rules(code: str) -> list[dict]:
    clean = _strip(code)
    probs = []
    for m in COLOR_FN.finditer(clean):
        args = m.group(2).strip()
        if args.startswith("{") and args.endswith("}"):
            args = args[1:-1]
        literal = [x.strip() for x in _split_commas(args)]
        nums = [float(x) for x in literal if NUM_ONLY.match(x)]
        if any(n > 1.0001 for n in nums):
            probs.append(problem("api", f"LOVE 11 colours are floats from 0 to 1, not 0-255: love.graphics.{m.group(1)}("
                                        f"{m.group(2).strip()[:40]}) is clamped to 1, so every mixed colour comes out wrong",
                                 clean.count("\n", 0, m.start()) + 1, name=f"love.graphics.{m.group(1)}",
                                 suggestion="divide by 255: 200/255 = 0.78"))
            break
    keys = _keys()
    for m in re.finditer(r"""\bkey\s*(?:==|~=)\s*(["'])(.*?)\1""", code):
        name = m.group(2)
        if keys and name not in keys:
            probs.append(problem("api", f"LOVE key name '{name}' does not exist", code.count("\n", 0, m.start()) + 1,
                                 name=name, suggestion=OLD_KEYS.get(name) or R["closest"](name, keys)))
    for m in re.finditer(r"love\.keyboard\.isDown\s*\(([^)]*)\)", code):
        for k in re.findall(r"""["']([^"']*)["']""", m.group(1)):
            if keys and k not in keys:
                probs.append(problem("api", f"LOVE key name '{k}' does not exist", code.count("\n", 0, m.start()) + 1,
                                     name=k, suggestion=OLD_KEYS.get(k) or R["closest"](k, keys)))
    for m in re.finditer(r"""(?:love\.mouse\.isDown\s*\(\s*|\bbutton\s*(?:==|~=)\s*)(["'])[lrm]\1""", code):
        probs.append(problem("api", "LOVE 11 mouse buttons are numbers (1 = left, 2 = right, 3 = middle), not strings",
                             code.count("\n", 0, m.start()) + 1, name="mouse button", suggestion="1, 2 or 3"))
        break
    return probs


