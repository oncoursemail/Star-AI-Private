"""Check every template of templates_src.json with the game's own parsers (McCheck in the lab container) on every
version, and write templates.json with the versions where each one is valid.

    MC_LAB=<user>@<brain1> python verify_templates.py      (run from server/mesh/mcdata/lab)
"""
import json
import os
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
VERSIONS = ["1.21", "1.21.1", "1.21.2", "1.21.3", "1.21.4", "1.21.5", "1.21.6", "1.21.7", "1.21.8", "1.21.9",
            "1.21.10", "1.21.11", "26.3"]


def main():
    lab = os.environ["MC_LAB"]
    src = json.loads((HERE.parent / "templates_src.json").read_text(encoding="utf-8"))
    jobs = []
    for t in src["commands"]:
        jobs.append({"id": "c:" + t["id"], "commands": [ln for ln in t["cmd"].split("\n") if ln.strip()]
                     + ([t["use"]] if t.get("use") else []), "files": {}})
    for t in src["files"]:
        jobs.append({"id": "f:" + t["id"], "commands": [t["use"]] if t.get("use") else [],
                     "files": {t["path"]: json.dumps(t["json"])}})
    data = "\n".join(json.dumps(j) for j in jobs) + "\n"
    subprocess.run(["ssh", lab, "cat > /tmp/tj.jsonl && lxc file push /tmp/tj.jsonl mc-data-lab/opt/lab/tj.jsonl "
                    ">/dev/null"], input=data.encode(), check=True)
    out = subprocess.run(["ssh", lab, "lxc exec mc-data-lab -- sh -c 'cd /opt/lab && JOBS=tj.jsonl sh runcheck.sh "
                          + " ".join(VERSIONS) + "'"], capture_output=True, check=True).stdout.decode()
    valid, errors, ver = {}, {}, None
    for line in out.splitlines():
        if line.startswith("== "):
            ver = line[3:].strip()
        elif line.startswith('{"id"'):
            d = json.loads(line)
            bad = [c.get("error") for c in d["commands"] if not c["ok"]]
            bad += [f.get("error") for f in d["files"] if f["ok"] is False and "Missing tag" not in (f.get("error") or "")]
            if not bad:
                valid.setdefault(d["id"], []).append(ver)
            else:
                errors.setdefault(d["id"], {})[ver] = bad[0][:200]
    res = {"note": "generated by lab/verify_templates.py: 'valid' = versions where the game's own parser/codec "
                   "accepts the template", "commands": [], "files": []}
    for t in src["commands"]:
        res["commands"].append({**t, "valid": valid.get("c:" + t["id"], [])})
    for t in src["files"]:
        res["files"].append({**t, "valid": valid.get("f:" + t["id"], [])})
    (HERE.parent / "templates.json").write_text(json.dumps(res, indent=1, ensure_ascii=False), encoding="utf-8")
    for k in [j["id"] for j in jobs]:
        print(f"{k:24} valid: {','.join(valid.get(k, [])) or '-'}" + (
            f"   first error: {next(iter(errors[k].values()))[:110]}" if k in errors and not valid.get(k) else ""))


if __name__ == "__main__":
    main()
